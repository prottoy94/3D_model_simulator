/**
 * Runnable code from a model: a Keras functional-API script or a PyTorch
 * nn.Module. Layer constructors come from the op catalog; this file adds the
 * wiring (which tensor feeds which layer) and the functional ops.
 *
 * Ops without a standard layer in the framework are written as a comment and
 * reported in `warnings`, so the script never silently drops a layer.
 */
import type { RuntimeIR, RuntimeNode } from "../ir/runtime";
import { getOp } from "../ops";
import { isImage, shapeText } from "../shapes/tensor";
import type { CodeListing } from "./listing";

export type ExportedCode = CodeListing & {
  framework: "keras" | "pytorch";
  /** Layers that could not be written as real code. */
  warnings: string[];
};

const identifier = (text: string, fallback: string) => {
  const cleaned = text
    .replace(/^n_/, "")
    .replace(/[^A-Za-z0-9_]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .toLowerCase();
  const safe = /^[a-z_]/.test(cleaned) ? cleaned : cleaned ? `v_${cleaned}` : fallback;
  return [
    "in",
    "is",
    "if",
    "or",
    "and",
    "not",
    "for",
    "def",
    "del",
    "as",
    "class",
    "pass",
    "input",
    "x",
  ].includes(safe)
    ? `${safe}_`
    : safe;
};

const className = (name: string) => {
  const parts = name.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const joined = parts.map((part) => part[0]!.toUpperCase() + part.slice(1)).join("");
  return /^[A-Za-z]/.test(joined) ? joined : `Model${joined}`;
};

type Line = { text: string; nodeId?: string };

class Script {
  readonly lines: Line[] = [];
  add(text = "", nodeId?: string): void {
    this.lines.push({ text, nodeId });
  }
  finish(framework: ExportedCode["framework"], warnings: string[]): ExportedCode {
    const lineOfNode: Record<string, number> = {};
    this.lines.forEach((line, index) => {
      if (line.nodeId) lineOfNode[line.nodeId] = index + 1;
    });
    return {
      text: this.lines.map((line) => line.text).join("\n") + "\n",
      language: "python",
      lineOfNode,
      linesOfGroup: {},
      framework,
      warnings,
    };
  }
}

function prepare(ir: RuntimeIR, modelId: string) {
  const model = ir.models.find((candidate) => candidate.id === modelId);
  const order = (ir.index.topoOrder[modelId] ?? []).map((id) => ir.nodes[id]!);
  const names = new Map<string, string>();
  const used = new Set<string>();
  for (const node of order) {
    let name = identifier(node.id, "layer");
    for (let n = 2; used.has(name); n++) name = `${identifier(node.id, "layer")}_${n}`;
    used.add(name);
    names.set(node.id, name);
  }
  const inputsOf = (node: RuntimeNode) =>
    (ir.index.inEdges[node.id] ?? []).map((edge) => names.get(edge.from)!);
  const sinks = order.filter((node) => (ir.index.outEdges[node.id] ?? []).length === 0);
  const outputs = (
    model?.outputNodeIds.length
      ? model.outputNodeIds.map((id) => ir.nodes[id]!).filter(Boolean)
      : sinks
  ).map((node) => names.get(node.id)!);
  return { model, order, names, inputsOf, outputs };
}

const io = (node: RuntimeNode) => ({ in: node.inShapes, out: node.outShape! });
const comment = (node: RuntimeNode) => (node.outShape ? `  # ${shapeText(node.outShape)}` : "");

/** Ops Keras has no built-in layer for; they need the user's own Layer class. */
const KERAS_CUSTOM = new Set([
  "patchify",
  "patch_embed",
  "pos_embed",
  "slice",
  "custom",
  "backbone",
  "roi_pool",
]);

export function exportKeras(ir: RuntimeIR, modelId: string): ExportedCode {
  const { model, order, names, inputsOf, outputs } = prepare(ir, modelId);
  const script = new Script();
  const warnings: string[] = [];
  const fn = `build_${identifier(model?.name ?? "model", "model")}`;

  script.add(`# ${model?.name ?? "Model"} — generated by NeuroScope Forge (Keras functional API)`);
  script.add("import keras");
  script.add("from keras import layers");
  script.add();
  script.add();
  script.add(`def ${fn}():`);
  const inputNames: string[] = [];
  for (const node of order) {
    const name = names.get(node.id)!;
    const spec = getOp(node.op);
    const sources = inputsOf(node);
    if (node.op === "input") {
      inputNames.push(name);
      script.add(
        `    ${name} = ${spec!.codegen.keras(node.params, io(node))}${comment(node)}`,
        node.id,
      );
      continue;
    }
    if (!spec || !node.outShape || node.status === "error" || KERAS_CUSTOM.has(node.op)) {
      warnings.push(
        `${node.label}: "${node.op}" has no standard Keras layer; write it yourself where the script says TODO.`,
      );
      script.add(
        `    ${name} = ${sources[0] ?? "None"}  # TODO: ${node.op} (${node.label}) is not a built-in Keras layer`,
        node.id,
      );
      continue;
    }
    let layer = spec.codegen.keras(node.params, io(node));
    if (node.wrapper === "time_distributed") layer = `layers.TimeDistributed(${layer})`;
    const call =
      node.op === "multi_head_attention"
        ? // Keras call order is (query, value, key).
          `(${[sources[0], sources[1] ?? sources[0], sources[2]].filter(Boolean).join(", ")})`
        : sources.length > 1
          ? `([${sources.join(", ")}])`
          : `(${sources[0]})`;
    script.add(`    ${name} = ${layer}${call}${comment(node)}`, node.id);
  }
  const list = (items: string[]) => (items.length === 1 ? items[0]! : `[${items.join(", ")}]`);
  script.add(
    `    return keras.Model(${list(inputNames)}, ${list(outputs)}, name=${JSON.stringify(model?.name ?? "model")})`,
  );
  script.add();
  script.add();
  script.add(`model = ${fn}()`);
  script.add("model.summary()");
  return script.finish("keras", warnings);
}

const TORCH_ACTIVATION: Record<string, (x: string) => string> = {
  relu: (x) => `F.relu(${x})`,
  gelu: (x) => `F.gelu(${x})`,
  sigmoid: (x) => `torch.sigmoid(${x})`,
  tanh: (x) => `torch.tanh(${x})`,
  silu: (x) => `F.silu(${x})`,
  swish: (x) => `F.silu(${x})`,
  softmax: (x) => `F.softmax(${x}, dim=-1)`,
};

/** How one node appears in PyTorch: an optional module in __init__ and an expression in forward. */
function torchNode(
  node: RuntimeNode,
  sources: string[],
  self: string,
): { module?: string; expr: string } | null {
  const spec = getOp(node.op);
  const x = sources[0] ?? "x";
  const p = node.params;
  switch (node.op) {
    case "add":
      return { expr: sources.join(" + ") };
    case "multiply":
      return { expr: sources.join(" * ") };
    case "concat":
      return { expr: `torch.cat([${sources.join(", ")}], dim=${Number(p.axis ?? 1)})` };
    case "flatten":
      return { expr: `torch.flatten(${x}, ${Number(p.startAxis ?? 1)})` };
    case "reshape":
      return { expr: `${x}.reshape(${x}.shape[0], ${(p.shape as number[]).join(", ")})` };
    case "softmax":
      return { expr: `F.softmax(${x}, dim=${Number(p.axis ?? -1)})` };
    case "relu":
    case "gelu":
    case "sigmoid":
      return { expr: TORCH_ACTIVATION[node.op]!(x) };
    case "global_avg_pool": {
      const input = node.inShapes[0];
      if (input && isImage(input)) {
        return { expr: p.keepDims ? `F.adaptive_avg_pool2d(${x}, 1)` : `${x}.mean(dim=(2, 3))` };
      }
      // A sequence: average over the tokens.
      return {
        expr: `${x}.mean(dim=${input?.layout === "NCL" ? 2 : 1}${p.keepDims ? ", keepdim=True" : ""})`,
      };
    }
    case "multi_head_attention":
      // forward(query, key, value); our input order is query, value, key.
      return {
        module: spec!.codegen.pytorch(p, io(node)),
        expr: `${self}(${x}, ${sources[2] ?? sources[1] ?? x}, ${sources[1] ?? x})[0]`,
      };
    case "conv2d":
    case "depthwise_conv2d":
    case "dense": {
      const activation = TORCH_ACTIVATION[String(p.activation ?? "linear")];
      const call = `${self}(${x})`;
      return {
        module: spec!.codegen.pytorch(p, io(node)),
        expr: activation ? activation(call) : call,
      };
    }
    case "maxpool2d":
    case "avgpool2d":
    case "batchnorm":
    case "layernorm":
    case "dropout":
    case "embedding":
      return { module: spec!.codegen.pytorch(p, io(node)), expr: `${self}(${x})` };
    case "groupnorm":
    case "upsample":
      return { module: spec!.codegen.pytorch(p, io(node)), expr: `${self}(${x})` };
    case "tanh":
      return { expr: `torch.tanh(${x})` };
    case "silu":
      return { expr: `F.silu(${x})` };
    case "leaky_relu":
      return { expr: `F.leaky_relu(${x})` };
    case "hardswish":
      return { expr: `F.hardswish(${x})` };
    case "global_max_pool": {
      const input = node.inShapes[0];
      const dims = input && isImage(input) ? "(2, 3)" : input?.layout === "NCL" ? "2" : "1";
      return { expr: `${x}.amax(dim=${dims}${p.keepDims ? ", keepdim=True" : ""})` };
    }
    case "rnn":
    case "lstm":
    case "gru":
      // The layer returns (outputs, state); the last time step is the summary of the sequence.
      return {
        module: spec!.codegen.pytorch(p, io(node)),
        expr: p.returnSequences ? `${self}(${x})[0]` : `${self}(${x})[0][:, -1]`,
      };
    default:
      return null;
  }
}

export function exportPytorch(ir: RuntimeIR, modelId: string): ExportedCode {
  const { model, order, names, inputsOf, outputs } = prepare(ir, modelId);
  const script = new Script();
  const warnings: string[] = [];
  const name = className(model?.name ?? "Net");
  const inputs = order.filter((node) => node.op === "input");

  const modules: Array<{ node: RuntimeNode; text: string }> = [];
  const forward: Array<{ node: RuntimeNode; text: string }> = [];
  for (const node of order) {
    if (node.op === "input") continue;
    const variable = names.get(node.id)!;
    const built =
      node.outShape && node.status !== "error"
        ? torchNode(node, inputsOf(node), `self.${variable}`)
        : null;
    if (!built) {
      warnings.push(
        `${node.label}: "${node.op}" could not be written as PyTorch code; write it yourself where the script says TODO.`,
      );
      forward.push({
        node,
        text: `${variable} = ${inputsOf(node)[0] ?? "None"}  # TODO: ${node.op} (${node.label})`,
      });
      continue;
    }
    if (built.module) modules.push({ node, text: `self.${variable} = ${built.module}` });
    forward.push({ node, text: `${variable} = ${built.expr}${comment(node)}` });
  }

  script.add(`# ${model?.name ?? "Model"} — generated by NeuroScope Forge (PyTorch)`);
  script.add("import torch");
  script.add("import torch.nn as nn");
  script.add("import torch.nn.functional as F");
  script.add();
  script.add();
  script.add(`class ${name}(nn.Module):`);
  script.add("    def __init__(self):");
  script.add("        super().__init__()");
  for (const entry of modules) script.add(`        ${entry.text}`);
  script.add();
  script.add(
    `    def forward(self, ${inputs.map((node) => names.get(node.id)!).join(", ") || "x"}):`,
  );
  for (const node of inputs)
    script.add(
      `        # ${names.get(node.id)}: ${node.outShape ? shapeText(node.outShape) : "input"}`,
      node.id,
    );
  for (const entry of forward) script.add(`        ${entry.text}`, entry.node.id);
  script.add(`        return ${outputs.join(", ") || "None"}`);
  script.add();
  script.add();
  script.add(`model = ${name}()`);
  script.add('print(sum(p.numel() for p in model.parameters()), "parameters")');
  const samples = inputs.map((node) => {
    const dims = (node.outShape?.dims ?? [])
      .slice(1)
      .map((dim) => (typeof dim === "number" ? dim : 4));
    return node.inShapes.length === 0 &&
      dims.length === 1 &&
      getOp("embedding") &&
      (ir.index.outEdges[node.id] ?? []).some((edge) => ir.nodes[edge.to]?.op === "embedding")
      ? `torch.randint(0, 10, (1, ${dims.join(", ")}))`
      : `torch.randn(1, ${dims.join(", ")})`;
  });
  script.add(`out = model(${samples.join(", ")})`);
  script.add("print(out.shape if hasattr(out, 'shape') else [o.shape for o in out])");
  return script.finish("pytorch", warnings);
}

export function exportCode(ir: RuntimeIR, modelId: string): ExportedCode {
  return ir.engineFramework === "pytorch" ? exportPytorch(ir, modelId) : exportKeras(ir, modelId);
}

/** The same script wrapped as a one-cell Jupyter notebook. */
export function exportNotebook(code: ExportedCode, title: string): string {
  return JSON.stringify(
    {
      nbformat: 4,
      nbformat_minor: 5,
      metadata: { language_info: { name: "python" } },
      cells: [
        {
          cell_type: "markdown",
          metadata: {},
          source: `# ${title}\n\nGenerated by NeuroScope Forge.`,
        },
        { cell_type: "code", metadata: {}, execution_count: null, outputs: [], source: code.text },
      ],
    },
    null,
    1,
  );
}
